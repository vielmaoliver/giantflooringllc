document.addEventListener("DOMContentLoaded", () => {
  const customOffsets = {
    services: -8,
    projects: 10,
    contact: 0,
    certifications: 20
  };

  document.querySelectorAll('a[href^="#"]').forEach((link) => {
    link.addEventListener("click", (event) => {
      const hash = link.getAttribute("href");
      if (!hash || hash === "#") return;

      const target = document.querySelector(hash);
      if (!target) return;

      event.preventDefault();

      const navbar = document.querySelector(".navbar");
      const navHeight = navbar ? navbar.getBoundingClientRect().height : 0;
      const key = hash.slice(1);
      const extra = Object.prototype.hasOwnProperty.call(customOffsets, key) ? customOffsets[key] : 0;
      const top = target.getBoundingClientRect().top + window.scrollY - navHeight + extra;

      window.scrollTo({ top, behavior: "smooth" });
      history.pushState(null, "", hash);

      const menu = document.querySelector(".navbar-collapse.show");
      if (menu && window.bootstrap) {
        bootstrap.Collapse.getOrCreateInstance(menu).hide();
      }
    });
  });
});



